#!/usr/bin/env python
"""The documentation's own checks (2 November 2026), run by the `docs-check` workflow on every pull request.

    python scripts/docs_check.py soup            # write docs/registers/soup.md from uv.lock and pyproject.toml
    python scripts/docs_check.py check           # fail on any problem below

What ``check`` verifies:

* **the SOUP list is current**: ``docs/registers/soup.md`` is what ``soup`` would write now from ``uv.lock``;
* **every risk control has its evidence**: each control in ``docs/registers/risks.yml`` names tests that exist
  (``tests/<file>.py::<test name>``), and each risk names its controls or says why it has none;
* **the two languages match**: ``docs/en`` and ``docs/it`` hold the same files, with the same number of sections
  (``##`` headings) and tables;
* **the risk table follows the register**: every risk id of the register is in both COMPLIANCE_RISK files;
* **links resolve**: every relative link in the documentation points to a file of the repository.
"""

from __future__ import annotations

import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
SOUP = DOCS / "registers" / "soup.md"
RISKS = DOCS / "registers" / "risks.yml"


def _name(requirement: str) -> str:
    return re.split(r"[\s\[<>=!~;@]", requirement.strip(), maxsplit=1)[0].lower().replace("_", "-")


def soup_text() -> str:
    project = tomllib.loads((ROOT / "pyproject.toml").read_text("utf-8"))["project"]
    groups: dict[str, set[str]] = {"core": {_name(r) for r in project.get("dependencies", [])}}
    for extra, reqs in sorted(project.get("optional-dependencies", {}).items()):
        groups[extra] = {_name(r) for r in reqs if not r.strip().lower().startswith("melampo")}
    lock = tomllib.loads((ROOT / "uv.lock").read_text("utf-8"))
    versions = {p["name"].lower().replace("_", "-"): p.get("version", "") for p in lock.get("package", [])}
    direct: dict[str, list[str]] = {}
    for group, names in groups.items():
        for n in names:
            direct.setdefault(n, []).append(group)
    lines = [
        "# Software of unknown provenance (SOUP)",
        "",
        "Generated by `python scripts/docs_check.py soup` from `pyproject.toml` and `uv.lock`; do not edit by hand.",
        "Models, ontologies and corpora, with their licences, are in `melampo-assets.yaml`.",
        "",
        f"Direct dependencies: {len(direct)}. Packages in the lock, transitive included: {len(versions)}.",
        "",
        "| Package | Locked version | Extras that need it |",
        "| --- | --- | --- |",
    ]
    for n in sorted(direct):
        lines.append(f"| {n} | {versions.get(n, 'not locked')} | {', '.join(sorted(direct[n]))} |")
    return "\n".join(lines) + "\n"


def _risks() -> list[dict]:
    import yaml

    return (yaml.safe_load(RISKS.read_text("utf-8")) or {}).get("risks", [])


def _test_exists(ref: str) -> bool:
    path, _, name = ref.partition("::")
    file = ROOT / path
    return file.exists() and re.search(rf"^def {re.escape(name)}\(", file.read_text("utf-8"), re.M) is not None


def _shape(path: Path) -> tuple[int, int]:
    text = path.read_text("utf-8")
    sections = len(re.findall(r"^## ", text, re.M))
    tables = len(re.findall(r"^\|[ -:|]+\|$", text, re.M))
    return sections, tables


def check() -> list[str]:
    problems = []
    if not SOUP.exists() or SOUP.read_text("utf-8") != soup_text():
        problems.append("docs/registers/soup.md is not current: run `python scripts/docs_check.py soup`")
    for risk in _risks():
        rid = risk.get("id", "?")
        controls = risk.get("controls") or []
        if not controls and not risk.get("no_control_because"):
            problems.append(f"{rid}: no control and no reason")
        for control in controls:
            tests = control.get("tests") or []
            if not tests and not control.get("verified_by"):
                problems.append(f"{rid}: control '{control.get('control', '')[:40]}' has no test")
            for t in tests:
                if not _test_exists(t):
                    problems.append(f"{rid}: test not found: {t}")
    for lang in ("en", "it"):
        table = DOCS / lang / "COMPLIANCE_RISK.md"
        if table.exists():
            text = table.read_text("utf-8")
            for risk in _risks():
                if f"| {risk.get('id')} |" not in text:
                    problems.append(f"{lang}/COMPLIANCE_RISK.md: risk {risk.get('id')} of the register is missing")
    en, it = DOCS / "en", DOCS / "it"
    en_files = {p.name for p in en.glob("*.md")}
    it_files = {p.name for p in it.glob("*.md")}
    if en_files != it_files:
        problems.append(f"docs/en and docs/it differ: {sorted(en_files ^ it_files)}")
    for name in sorted(en_files & it_files):
        if _shape(en / name) != _shape(it / name):
            problems.append(f"{name}: sections or tables differ between en {_shape(en / name)} and it {_shape(it / name)}")
    for md in list(DOCS.rglob("*.md")) + [ROOT / "README.md", ROOT / "CONTRIBUTING.md"]:
        if not md.exists():
            continue
        for target in re.findall(r"\]\(([^)#\s]+)(?:#[^)]*)?\)", md.read_text("utf-8")):
            if re.match(r"[a-z]+://|mailto:", target):
                continue
            if not (md.parent / target).resolve().exists():
                problems.append(f"{md.relative_to(ROOT)}: broken link {target}")
    return problems


def main(argv: list[str]) -> int:
    if argv[:1] == ["soup"]:
        SOUP.parent.mkdir(parents=True, exist_ok=True)
        SOUP.write_text(soup_text(), "utf-8")
        print(f"wrote {SOUP.relative_to(ROOT)}")
        return 0
    if argv[:1] == ["check"]:
        problems = check()
        for p in problems:
            print(f"::error::{p}")
        print("documentation: ok" if not problems else f"documentation: {len(problems)} problem(s)")
        return 1 if problems else 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
